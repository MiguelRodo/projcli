use std::{fs,path::Path,process::Command};

fn invoke(root:&Path,mode:&str,explicit:Option<&str>,env:Option<&str>)->std::process::Output {
    let mut cmd=Command::new(env!("CARGO_BIN_EXE_proj"));
    cmd.args([mode,"--non-interactive","--project"]).arg(root).current_dir(root)
        .env_remove(proj::PROJECT_ROOT_ENV).env_remove(proj::RUN_CONTEXT_ENV).env_remove("PROJR_PROFILE").env_remove("QUARTO_PROFILE").env_remove("PROJR_CLEAR_OUTPUT");
    if let Some(value)=explicit {cmd.args(["--output-clear-stage",value]);}
    if let Some(value)=env {cmd.env("PROJR_CLEAR_OUTPUT",value);}
    cmd.output().unwrap()
}

#[test]
fn lifecycle_orders_hooks_clear_stages_promotion_and_version_without_publishing_preview() {
    for mode in ["build","build-dev"] {
      for stage in ["none","pre","post"] {
       for fail in [false,true] {
        let temp=tempfile::tempdir().unwrap();let root=temp.path().canonicalize().unwrap();
        fs::create_dir(root.join("released")).unwrap();fs::create_dir(root.join("cache")).unwrap();
        fs::write(root.join("released/old.txt"),"previous release").unwrap();fs::write(root.join("VERSION"),"v1.2.3-4\n").unwrap();
        let config=format!("directories:\n  cache:\n    path: cache\n  output:\n    path: released\nsettings:\n  output-clear-stage: {stage}\nbuild:\n  scripts: [analysis.py]\n  hooks:\n    pre: [start.py]\n    post: [end.py]\n  git: false\n  restrictions:\n    not_behind: false\n");
        fs::write(root.join("_proj.yml"),&config).unwrap();
        fs::write(root.join("start.py"),"from pathlib import Path\nassert Path('released/old.txt').read_text()=='previous release'\nassert not Path('.gitignore').exists()\nPath('cache/events').write_text('start\\n')\n").unwrap();
        let dev=mode=="build-dev";
        let pre=stage=="pre"&&!dev;
        let binary=serde_json::to_string(env!("CARGO_BIN_EXE_proj")).unwrap();
        fs::write(root.join("analysis.py"),format!(r#"from pathlib import Path
import json,subprocess
assert Path('released/old.txt').exists()=={old_exists}
value=json.loads(subprocess.check_output([{binary},'--machine','path','get','--label','output','--target','safe','new.txt'],text=True))
target=Path(value['result']['path']);target.parent.mkdir(parents=True,exist_ok=True);target.write_text('fresh generated bytes')
with Path('cache/events').open('a') as stream: stream.write('analysis\n')
raise SystemExit({exit_code})
"#,old_exists=if pre {"False"}else{"True"},exit_code=if fail {17}else{0})).unwrap();
        fs::write(root.join("end.py"),format!(r#"from pathlib import Path
assert Path('released/old.txt').exists()=={old_exists}
assert Path('released/new.txt').exists()=={new_exists}
assert Path('VERSION').read_text()=='v1.2.3-4\n'
with Path('cache/events').open('a') as stream: stream.write('end\n')
"#,old_exists=if dev||stage=="none" {"True"}else{"False"},new_exists=if dev {"False"}else{"True"})).unwrap();
        let output=invoke(&root,mode,None,Some("pre")); // explicit YAML also beats this environment.
        assert_eq!(output.status.success(),!fail,"{mode}/{stage}/fail={fail}: {} {}",String::from_utf8_lossy(&output.stdout),String::from_utf8_lossy(&output.stderr));
        let events=fs::read_to_string(root.join("cache/events")).unwrap();
        assert_eq!(events.lines().collect::<Vec<_>>(),if fail {vec!["start","analysis"]}else{vec!["start","analysis","end"]});
        let key=if dev {"v1.2.3-4"}else{"v1.2.4"};
        assert_eq!(fs::read_to_string(root.join("cache/projr").join(key).join("output/new.txt")).unwrap(),"fresh generated bytes");
        if fail||dev {
            assert_eq!(fs::read_to_string(root.join("VERSION")).unwrap(),"v1.2.3-4\n");
            assert_eq!(fs::read_to_string(root.join("released/old.txt")).unwrap(),"previous release");assert!(!root.join("released/new.txt").exists());
        } else {
            assert_eq!(fs::read_to_string(root.join("released/new.txt")).unwrap(),"fresh generated bytes");
            assert_eq!(root.join("released/old.txt").exists(),stage=="none");
            let version=proj::version_get_from(camino::Utf8Path::from_path(&root).unwrap()).unwrap();assert_eq!((version.major,version.minor,version.patch,version.dev),(1,2,4,1));
        }
        assert_eq!(fs::read_to_string(root.join("_proj.yml")).unwrap(),config);
       }
      }
    }
}

#[test]
fn clear_policy_defaults_none_and_explicit_cli_overrides_yaml_then_legacy_environment() {
    for (settings,explicit,environment,old_remains) in [
        ("",None,None,true),
        ("",None,Some("never"),true),
        ("",None,Some("post"),false),
        ("settings:\n  output-clear-stage: none\n",None,Some("pre"),true),
        ("settings:\n  output-clear-stage: pre\n",Some("none"),Some("post"),true),
    ] {
        let temp=tempfile::tempdir().unwrap();let root=temp.path();fs::create_dir(root.join("released")).unwrap();fs::write(root.join("released/old"),"prior").unwrap();
        fs::write(root.join("_proj.yml"),format!("directories:\n  cache: {{path: cache}}\n  output: {{path: released}}\n{settings}build:\n  scripts: [analysis.py]\n  git: false\n")).unwrap();
        fs::write(root.join("analysis.py"),"pass\n").unwrap();
        let output=invoke(root,"build",explicit,environment);assert!(output.status.success(),"{}",String::from_utf8_lossy(&output.stderr));
        assert_eq!(root.join("released/old").exists(),old_remains);
    }
}

#[test]
fn invalid_settings_in_active_layers_fail_before_start_hooks_or_state_writes() {
    for value in ["null","true","invalid","never"] {
      for layer in ["_proj.yml","_projr-local.yml"] {
        let temp=tempfile::tempdir().unwrap();let root=temp.path();
        let base="settings:\n  output-clear-stage: none\nbuild:\n  scripts: []\n  hooks:\n    pre: [start.py]\n";
        fs::write(root.join("_proj.yml"),base).unwrap();
        let content=format!("settings:\n  output-clear-stage: {value}\n");
        fs::write(root.join(layer),if layer=="_proj.yml" {format!("{content}build:\n  scripts: []\n  hooks:\n    pre: [start.py]\n")}else{content}).unwrap();
        fs::write(root.join("start.py"),"open('ran','w').write('bad')\n").unwrap();
        let output=invoke(root,"build-dev",None,None);assert!(!output.status.success(),"accepted {value} in {layer}");
        assert!(!root.join("ran").exists());assert!(!root.join("VERSION").exists());assert!(!root.join(".gitignore").exists());
      }
    }
}


#[cfg(unix)]
#[test]
fn successful_render_preserves_native_artifacts_and_promotes_only_fresh_bytes() {
    use std::os::unix::fs::PermissionsExt;
    for extension in ["qmd","Rmd"] {
        let temp=tempfile::tempdir().unwrap();let root=temp.path().canonicalize().unwrap();
        for directory in ["analysis/report_files/empty","bin","published"] {fs::create_dir_all(root.join(directory)).unwrap();}
        fs::write(root.join("analysis/report.html"),b"prior native html").unwrap();
        fs::write(root.join("analysis/report_files/old.bin"),b"prior native asset").unwrap();
        fs::write(root.join("published/old.html"),b"prior published html").unwrap();
        fs::write(root.join("VERSION"),"v1.2.3-4\n").unwrap();
        fs::write(root.join(format!("analysis/report.{extension}")),"Report\n").unwrap();
        fs::write(root.join("_proj.yml"),format!("directories:\n  cache: {{path: cache}}\n  Docs: {{path: published}}\nbuild:\n  scripts: [analysis/report.{extension}]\n  git: false\n")).unwrap();
        let fake=r#"#!/usr/bin/env python3
import os,sys,json
from pathlib import Path
if '--version' in sys.argv: raise SystemExit(0)
if sys.argv[1:2]==['-e'] and 'rmarkdown::render(' not in sys.argv[2]: raise SystemExit(0)
context=json.loads(Path(os.environ['PROJ_RUN_CONTEXT']).read_text())
document=Path(context['render']['document'])
document.with_suffix('.html').write_bytes(b'fresh html')
assets=document.parent/(document.stem+'_files');assets.mkdir(exist_ok=True)
(assets/'new.bin').write_bytes(b'fresh asset')
"#;
        for name in ["quarto","Rscript"] {let executable=root.join("bin").join(name);fs::write(&executable,fake).unwrap();fs::set_permissions(executable,fs::Permissions::from_mode(0o755)).unwrap();}
        let mut paths=vec![root.join("bin")];paths.extend(std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default()));
        let output=Command::new(env!("CARGO_BIN_EXE_proj")).args(["build","--non-interactive","--project"]).arg(&root).current_dir(&root)
            .env("PATH",std::env::join_paths(paths).unwrap()).env_remove(proj::PROJECT_ROOT_ENV).env_remove(proj::RUN_CONTEXT_ENV).env_remove("PROJR_PROFILE").env_remove("QUARTO_PROFILE").env_remove("PROJR_CLEAR_OUTPUT").output().unwrap();
        assert!(output.status.success(),"{}",String::from_utf8_lossy(&output.stderr));
        assert_eq!(fs::read(root.join("analysis/report.html")).unwrap(),b"prior native html");
        assert_eq!(fs::read(root.join("analysis/report_files/old.bin")).unwrap(),b"prior native asset");
        assert!(root.join("analysis/report_files/empty").is_dir());assert!(!root.join("analysis/report_files/new.bin").exists());
        for directory in ["published","cache/projr/v1.2.4/Docs"] {
            assert_eq!(fs::read(root.join(directory).join("report.html")).unwrap(),b"fresh html");
            assert_eq!(fs::read(root.join(directory).join("report_files/new.bin")).unwrap(),b"fresh asset");
            assert!(!root.join(directory).join("report_files/old.bin").exists());
        }
    }
}
